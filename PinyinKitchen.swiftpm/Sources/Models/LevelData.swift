import Foundation

public enum LevelMode: String, Codable, Sendable {
    case split = "split"   // 两拼音节：声母 + 韵母 + 声调
    case tri   = "tri"     // 三拼音节：声母 + 介音 + 韵母 + 声调
    case whole = "whole"   // 整体认读音节：整体音节 + 声调
}

public struct PinyinWord: Identifiable, Equatable, Hashable, Sendable {
    public let id: String
    public let levelNumber: Int
    public let mode: LevelMode
    public let initial: String?     // 声母 (split / tri)
    public let medial: String?      // 介音 (tri: i / u / ü)
    public let tonedFinal: String   // 带调韵母 (split / tri) 或 带调整体认读音节 (whole)
    public let character: String    // 目标汉字

    public init(levelNumber: Int, mode: LevelMode, parts: [String]) {
        self.levelNumber = levelNumber
        self.mode = mode
        switch mode {
        case .whole:
            self.initial = nil
            self.medial = nil
            self.tonedFinal = parts[0]
            self.character = parts[1]
        case .tri:
            self.initial = parts[0]
            self.medial = parts[1]
            self.tonedFinal = parts[2]
            self.character = parts[3]
        case .split:
            self.initial = parts[0]
            self.medial = nil
            self.tonedFinal = parts[1]
            self.character = parts[2]
        }
        self.id = "\(levelNumber)|\(Self.computeSyllable(mode: mode, initial: self.initial, medial: self.medial, tonedFinal: self.tonedFinal))|\(self.character)"
    }

    public var fullSyllable: String {
        Self.computeSyllable(mode: mode, initial: initial, medial: medial, tonedFinal: tonedFinal)
    }

    /// 无调韵母母体（如 ā -> a, uī -> ui, ǖ -> ü）或无调整体认读音节（如 zhī -> zhi）
    public var baseFinal: String {
        PinyinHelper.stripTone(tonedFinal)
    }

    /// 声调数字 1...4
    public var toneNumber: Int {
        PinyinHelper.toneNumber(of: tonedFinal)
    }

    /// 是否触发「j q x 遇到 ü 去两点」规则
    public var triggersJQXRule: Bool {
        guard let ini = initial, ["j", "q", "x"].contains(ini) else { return false }
        if mode == .tri && medial == "ü" { return true }
        if mode == .split {
            let b = baseFinal
            return b == "u" || b == "ue" || b == "un" || b.hasPrefix("ü")
        }
        return false
    }

    public static func computeSyllable(mode: LevelMode, initial: String?, medial: String?, tonedFinal: String) -> String {
        switch mode {
        case .whole:
            return tonedFinal
        case .tri:
            let ini = initial ?? ""
            var med = medial ?? ""
            if ["j", "q", "x"].contains(ini) && med == "ü" {
                med = "u"
            }
            return ini + med + tonedFinal
        case .split:
            return (initial ?? "") + tonedFinal
        }
    }
}

public struct LevelDefinition: Identifiable, Sendable {
    public let id: Int
    public let name: String
    public let subtitle: String
    public let mode: LevelMode
    public let tip: String?
    public let words: [PinyinWord]

    public var shortName: String {
        name.replacingOccurrences(of: #"^第 \d+ 关 · "#, with: "", options: .regularExpression)
    }
}

public enum PinyinHelper {
    public static let initialOrder: [String] = [
        "b","p","m","f","d","t","n","l","g","k","h",
        "j","q","x","zh","ch","sh","r","z","c","s"
    ]

    public static let finalOrder: [String] = [
        "a","o","e","i","u","ü",
        "ai","ei","ui","ao","ou","iu","ie","üe","ue","er",
        "an","en","in","un","ün",
        "ang","eng","ing","ong"
    ]

    public static let wholeOrder: [String] = [
        "zhi","chi","shi","ri","zi","ci","si",
        "yi","wu","yu","ye","yue","yuan","yin","yun","ying"
    ]

    private static let toneCharToBase: [Character: (base: Character, tone: Int)] = [
        "ā": ("a", 1), "á": ("a", 2), "ǎ": ("a", 3), "à": ("a", 4),
        "ō": ("o", 1), "ó": ("o", 2), "ǒ": ("o", 3), "ò": ("o", 4),
        "ē": ("e", 1), "é": ("e", 2), "ě": ("e", 3), "è": ("e", 4),
        "ī": ("i", 1), "í": ("i", 2), "ǐ": ("i", 3), "ì": ("i", 4),
        "ū": ("u", 1), "ú": ("u", 2), "ǔ": ("u", 3), "ù": ("u", 4),
        "ǖ": ("ü", 1), "ǘ": ("ü", 2), "ǚ": ("ü", 3), "ǜ": ("ü", 4)
    ]

    private static let baseToToned: [Character: [Character]] = [
        "a": ["ā", "á", "ǎ", "à"],
        "o": ["ō", "ó", "ǒ", "ò"],
        "e": ["ē", "é", "ě", "è"],
        "i": ["ī", "í", "ǐ", "ì"],
        "u": ["ū", "ú", "ǔ", "ù"],
        "ü": ["ǖ", "ǘ", "ǚ", "ǜ"]
    ]

    /// 去除声调符号，保留原韵母字母（如 ā -> a, ǖ -> ü, uī -> ui）
    public static func stripTone(_ s: String) -> String {
        String(s.map { toneCharToBase[$0]?.base ?? $0 })
    }

    /// 提取声调数字 (1...4)，默认返回 1
    public static func toneNumber(of s: String) -> Int {
        for ch in s {
            if let info = toneCharToBase[ch] {
                return info.tone
            }
        }
        return 1
    }

    /// 标准汉语拼音标调规则：「有 a 找 a，没 a 找 o e，i u 并列标在后」
    public static func applyTone(base: String, tone: Int) -> String {
        guard (1...4).contains(tone) else { return base }
        let idx = tone - 1
        var chars = Array(stripTone(base))

        // 1. 有 a 找 a
        if let aIndex = chars.firstIndex(of: "a"), let toned = baseToToned["a"]?[idx] {
            chars[aIndex] = toned
            return String(chars)
        }
        // 2. 没 a 找 o e
        if let oIndex = chars.firstIndex(of: "o"), let toned = baseToToned["o"]?[idx] {
            chars[oIndex] = toned
            return String(chars)
        }
        if let eIndex = chars.firstIndex(of: "e"), let toned = baseToToned["e"]?[idx] {
            chars[eIndex] = toned
            return String(chars)
        }
        // 3. i u 并列标在后 (iu -> 标在 u; ui -> 标在 i)
        if base.contains("iu"), let uIndex = chars.lastIndex(of: "u"), let toned = baseToToned["u"]?[idx] {
            chars[uIndex] = toned
            return String(chars)
        }
        if base.contains("ui"), let iIndex = chars.lastIndex(of: "i"), let toned = baseToToned["i"]?[idx] {
            chars[iIndex] = toned
            return String(chars)
        }
        // 4. 单个 i / u / ü
        for v in [Character("i"), Character("u"), Character("ü")] {
            if let vIndex = chars.firstIndex(of: v), let toned = baseToToned[v]?[idx] {
                chars[vIndex] = toned
                return String(chars)
            }
        }
        return base
    }

    public static func finalCategory(for base: String) -> String {
        let single = ["a","o","e","i","u","ü"]
        let compound = ["ai","ei","ui","ao","ou","iu","ie","üe","ue","er"]
        let frontNasal = ["an","en","in","un","ün"]
        let backNasal = ["ang","eng","ing","ong"]
        if single.contains(base) { return "单韵母" }
        if compound.contains(base) { return "复韵母" }
        if frontNasal.contains(base) { return "前鼻韵母" }
        if backNasal.contains(base) { return "后鼻韵母" }
        return "其他韵母"
    }
}

