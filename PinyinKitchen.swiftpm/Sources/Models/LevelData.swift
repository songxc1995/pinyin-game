    public static let allUniqueCharacters: [String] = {
        var seen = Set<String>()
        var result: [String] = []
        for lv in levels {
            for w in lv.words {
                if !seen.contains(w.character) {
                    seen.insert(w.character)
                    result.append(w.character)
                }
            }
        }
        return result
    }()

    public static func readings(of ch: String) -> [String] {
        var seen = Set<String>()
        var out: [String] = []
        for lv in levels {
            for w in lv.words where w.character == ch {
                let py = w.fullSyllable
                if !seen.contains(py) {
                    seen.insert(py)
                    out.append(py)
                }
            }
        }
        return out
    }

    public static func firstLevel(for ch: String) -> Int {
        for lv in levels {
            if lv.words.contains(where: { $0.character == ch }) {
                return lv.id
            }
        }
        return 1
    }
